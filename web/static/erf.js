// The high word / low word trick of fdlibm: exp(-z*z-0.5625) with z = x rounded to its upper 32 bits.
const f64 = new Float64Array(1), u32 = new Uint32Array(f64.buffer);
function truncLow(x) { f64[0] = x; u32[0] = 0; return f64[0]; }

export function erf(x) {
  if (Number.isNaN(x)) return NaN;
  if (!Number.isFinite(x)) return x > 0 ? 1 : -1;
  const sign = x < 0 ? -1 : 1, ax = Math.abs(x);
  if (ax < 0.84375) {
    if (ax < 3.7252902984e-09) return ax < 2.848094538889218e-306 ? 0.125 * (8.0 * x + EFX8 * x) : x + 1.28379167095512586316e-01 * x;
    const z = x * x;
    const r = PP[0] + z * (PP[1] + z * (PP[2] + z * (PP[3] + z * PP[4])));
    const s = 1 + z * (QQ[0] + z * (QQ[1] + z * (QQ[2] + z * (QQ[3] + z * QQ[4]))));
    return x + x * (r / s);
  }
  if (ax < 1.25) {
    const s = ax - 1;
    const P = PA[0] + s * (PA[1] + s * (PA[2] + s * (PA[3] + s * (PA[4] + s * (PA[5] + s * PA[6])))));
    const Q = 1 + s * (QA[0] + s * (QA[1] + s * (QA[2] + s * (QA[3] + s * (QA[4] + s * QA[5])))));
    return sign * (ERX + P / Q);
  }
  if (ax >= 6) return sign * (1 - 1e-300);
  const s = 1 / (ax * ax);
  let R, S;
  if (ax < 1 / 0.35) {
    R = RA[0] + s * (RA[1] + s * (RA[2] + s * (RA[3] + s * (RA[4] + s * (RA[5] + s * (RA[6] + s * RA[7]))))));
    S = 1 + s * (SA[0] + s * (SA[1] + s * (SA[2] + s * (SA[3] + s * (SA[4] + s * (SA[5] + s * (SA[6] + s * SA[7])))))));
  } else {
    R = RB[0] + s * (RB[1] + s * (RB[2] + s * (RB[3] + s * (RB[4] + s * (RB[5] + s * RB[6])))));
    S = 1 + s * (SB[0] + s * (SB[1] + s * (SB[2] + s * (SB[3] + s * (SB[4] + s * (SB[5] + s * SB[6]))))));
  }
  const z = truncLow(ax);
  const r = Math.exp(-z * z - 0.5625) * Math.exp((z - ax) * (z + ax) + R / S);
  return sign * (1 - r / ax);
}
